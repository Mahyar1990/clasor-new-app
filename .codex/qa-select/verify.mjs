import { pathToFileURL } from 'node:url';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const { chromium } = await import(pathToFileURL(process.env.TEMP + '/clasor-design-qa/node_modules/playwright/index.mjs').href);
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe' });
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('http://localhost:3101', { waitUntil: 'networkidle' });
  const role = page.getByRole('combobox', { name: 'نقش نمایشی', exact: true });
  assert((await role.innerText()).includes('نویسنده'));
  assert.equal(await role.evaluate(el => el.tagName), 'BUTTON');
  await role.focus(); await page.keyboard.press('ArrowDown');
  await page.getByRole('listbox').waitFor();
  await page.keyboard.press('End'); await page.keyboard.press('Enter');
  await page.getByRole('listbox').waitFor({ state: 'hidden' });
  assert((await role.innerText()).includes('مهمان'));
  assert(await role.evaluate(el => document.activeElement === el));
  await role.click(); await page.keyboard.press('Home'); await page.keyboard.press('Escape');
  await page.getByRole('listbox').waitFor({ state: 'hidden' });
  assert((await role.innerText()).includes('مهمان'));
  assert(await page.getByRole('combobox', { name: 'نقش قفل‌شده', exact: true }).isDisabled());
  const invalid = page.getByRole('combobox', { name: 'نمونه خطای انتخاب', exact: false });
  assert.equal(await invalid.getAttribute('aria-invalid'), 'true');
  assert((await invalid.innerText()).includes('یک گزینه انتخاب کنید'));
  await invalid.click(); assert(await page.getByRole('option', { name: 'مهمان', exact: true }).isDisabled());
  assert.equal(await page.getByRole('listbox').evaluate(el => getComputedStyle(el).direction), 'rtl');
  await page.keyboard.press('Escape'); await page.getByRole('listbox').waitFor({ state: 'hidden' });
  await page.setViewportSize({ width: 360, height: 900 });
  await role.click(); const popup = page.getByRole('listbox'); await popup.waitFor();
  await popup.evaluate(async el => { await Promise.all(el.getAnimations().map(animation => animation.finished.catch(() => {}))); });
  const bounds = await popup.boundingBox(); assert(bounds.x >= -1 && bounds.x + bounds.width <= 361);
  await page.addScriptTag({ path: process.env.TEMP + '/clasor-design-qa/node_modules/axe-core/axe.min.js' });
  const violations = await page.evaluate(async () => (await axe.run('[data-slot=select-content]', { runOnly: { type: 'tag', values: ['wcag2a', 'wcag2aa', 'wcag21aa'] } })).violations.map(item => item.id));
  assert.deepEqual(violations, []); assert.deepEqual(errors, []);
  await page.screenshot({ path: '.codex/qa-select/mobile.png' });
  fs.writeFileSync('.codex/qa-select/report.json', JSON.stringify({ keyboardEndEnter: true, escapePreservesValue: true, focusReturn: true, disabled: true, invalid: true, placeholder: true, disabledOption: true, rtl: true, mobileBounds: bounds, axeViolations: violations, errors }, null, 2));
  console.log('Base UI Select: keyboard, focus, disabled/invalid, RTL, mobile and axe passed.');
} finally { await browser.close(); }
